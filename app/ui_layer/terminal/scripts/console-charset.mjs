/**
 * Regenerates src/text/consoleCharset.ts: the characters the classic Windows
 * console can draw. That console has no font fallback, so a character its
 * font lacks shows as a box with a question mark. Its stock fonts are
 * Consolas (the default) and Lucida Console (the PowerShell shortcuts); the
 * safe set is what both of them map. Run on Windows:
 *
 *   node scripts/console-charset.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const FONTS = ['lucon.ttf', 'consola.ttf']
const fontDir = join(process.env.SystemRoot ?? 'C:\\Windows', 'Fonts')

/** Code points a TrueType font maps, from its Windows Unicode cmap (format 4 or 12). */
function cmapOf(file) {
  const buf = readFileSync(file)
  const tables = buf.readUInt16BE(4)
  let cmap = -1
  for (let i = 0; i < tables; i++) {
    const rec = 12 + i * 16
    if (buf.toString('latin1', rec, rec + 4) === 'cmap') cmap = buf.readUInt32BE(rec + 8)
  }
  if (cmap < 0) throw new Error(`${file}: no cmap table`)
  const subtables = buf.readUInt16BE(cmap + 2)
  const points = new Set()
  for (let i = 0; i < subtables; i++) {
    const rec = cmap + 4 + i * 8
    const platform = buf.readUInt16BE(rec)
    const encoding = buf.readUInt16BE(rec + 2)
    const at = cmap + buf.readUInt32BE(rec + 4)
    if (platform !== 3 || (encoding !== 1 && encoding !== 10)) continue
    const format = buf.readUInt16BE(at)
    if (format === 4) {
      const segs = buf.readUInt16BE(at + 6) / 2
      const ends = at + 14
      const starts = ends + segs * 2 + 2
      const deltas = starts + segs * 2
      const offsets = deltas + segs * 2
      for (let s = 0; s < segs; s++) {
        const end = buf.readUInt16BE(ends + s * 2)
        const start = buf.readUInt16BE(starts + s * 2)
        const delta = buf.readInt16BE(deltas + s * 2)
        const offset = buf.readUInt16BE(offsets + s * 2)
        for (let c = start; c <= end && c !== 0xffff; c++) {
          let glyph
          if (offset === 0) glyph = (c + delta) & 0xffff
          else {
            const g = buf.readUInt16BE(offsets + s * 2 + offset + (c - start) * 2)
            glyph = g === 0 ? 0 : (g + delta) & 0xffff
          }
          if (glyph !== 0) points.add(c)
        }
      }
    } else if (format === 12) {
      const groups = buf.readUInt32BE(at + 12)
      for (let g = 0; g < groups; g++) {
        const rec12 = at + 16 + g * 12
        const start = buf.readUInt32BE(rec12)
        const end = buf.readUInt32BE(rec12 + 4)
        for (let c = start; c <= end; c++) points.add(c)
      }
    }
  }
  return points
}

const sets = FONTS.map(f => cmapOf(join(fontDir, f)))
const safe = [...sets[0]].filter(c => c > 0x7e && sets.every(s => s.has(c))).sort((a, b) => a - b)

const ranges = []
for (const c of safe) {
  const last = ranges[ranges.length - 1]
  if (last && last[1] === c - 1) last[1] = c
  else ranges.push([c, c])
}
const hex = n => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`
const body = ranges.map(([a, b]) => (a === b ? `  [${hex(a)}, ${hex(a)}],` : `  [${hex(a)}, ${hex(b)}],`)).join('\n')

const out = `/**
 * Generated by scripts/console-charset.mjs; do not edit by hand.
 *
 * Non-ASCII characters both stock fonts of the classic Windows console
 * (${FONTS.join(', ')}) draw: inclusive code point ranges.
 */
export const CONSOLE_RANGES: readonly (readonly [number, number])[] = [
${body}
]
`
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'text', 'consoleCharset.ts')
writeFileSync(target, out, 'utf8')
console.log(`${safe.length} characters in ${ranges.length} ranges -> ${target}`)
