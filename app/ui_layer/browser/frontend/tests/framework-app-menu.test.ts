import { openFrameworkSettings } from './helpers/framework-settings'
import { expect, test, type Page } from '@playwright/test'

const app = { id: 'studio', name: 'Development Studio', path: '/framework/studio', status: 'running' }
const registry = (page: Page) => page.getByRole('region', { name: 'Discovered apps', exact: true })
const requests = (page: Page) => page.evaluate(() => (window as any).panelRequests.filter((r: any) => r.type === 'agent_app_framework_request' && r.operation === 'manage'))
const send = (page: Page, type: string, data: unknown) => page.evaluate(({ type, data }) => (window as any).panelReceive({ type, data }), { type, data })
const list = (page: Page, apps = [app]) => send(page, 'agent_app_framework_list', { status: 'success', data: { apps, connected: [] } })
const reply = (page: Page, requestId: string, result: unknown) => send(page, 'agent_app_framework_response', { requestId, status: 'success', result })
async function setup(page: Page) {
  await page.setViewportSize({ width: 1280, height: 850 })
  await page.goto('/tests/panel-agent-apps.html?permissions-menu')
  await expect(page.getByRole('button', { name: 'Collapse sidebar', exact: true })).toBeVisible()
  await list(page)
}
async function menu(page: Page) {
  await page.getByRole('button', { name: 'Options: Development Studio', exact: true }).click()
}
async function openApp(page: Page) {
  await page.getByRole('button', { name: 'Open Development Studio', exact: true }).click()
  const last = () => page.evaluate(() => (window as any).panelRequests.filter((r: any) => r.type === 'agent_app_framework_open').at(-1))
  await expect.poll(async () => (await last())?.appId).toBe(app.id)
  await send(page, 'agent_app_framework_open', { requestId: (await last()).requestId, status: 'success', data: { ...app, url: 'http://localhost:7935/tests/fixtures/panel-app.html' } })
  await expect(page.frameLocator('iframe[data-framework]').getByRole('textbox', { name: 'App note' })).toBeVisible()
}

test('mobile app menus remain clickable above the real sidebar backdrop', async ({ page }, info) => {
  await page.setViewportSize({ width: 600, height: 850 })
  await page.goto('/tests/panel-agent-apps.html?mobile-layout')
  await expect(page.getByRole('button', { name: 'Open menu', exact: true })).toBeVisible()
  await list(page, [{ ...app, status: 'stopped' }])
  await page.getByRole('button', { name: 'Open menu', exact: true }).click()
  await menu(page)
  await expect(page.getByRole('menu').getByRole('button')).toHaveText(['Start', 'Delete'])
  await page.screenshot({ path: info.outputPath('mobile-app-menu.png') })
  await page.getByRole('menu').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Development Studio')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(await requests(page)).toEqual([])
})

test('successful CLI diagnostics stay out of settings and the app fills its view', async ({ page }, info) => {
  await setup(page)
  await send(page, 'agent_app_framework_lifecycle', { path: app.path, appId: app.id, requestId: 'started', operation: 'start', status: 'success', stderr: 'Live server ready on port 8123.' })
  await openApp(page)
  await expect(registry(page).locator('details')).toHaveCount(0)
  const view = page.getByRole('region', { name: 'App view', exact: true })
  await expect(view.locator('header')).toHaveCount(0)
  await expect(view.getByRole('button')).toHaveCount(0)
  await expect(page.getByText('Conversation and app settings')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('app-without-wrapper.png') })
  await menu(page)
  await expect(page.getByRole('menu').getByRole('button')).toHaveText(['Stop', 'Delete'])
  await openFrameworkSettings(page, 'Development Studio')
  const dialog = page.getByRole('article', { name: 'Development Studio settings' })
  await expect(dialog.getByRole('button', { name: 'Advanced', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'Open conversation', exact: true })).toHaveCount(0)
  await expect(dialog.getByText('Agent-App details', { exact: true })).toHaveCount(0)
  await expect(dialog.getByText('Live server ready on port 8123.')).toHaveCount(0)
  await openApp(page)
  await expect(page.frameLocator('iframe[data-framework]').getByRole('textbox', { name: 'App note' })).toBeVisible()
})

test('Delete confirms the exact app, prevents duplicate requests and disposes its view after success', async ({ page }, info) => {
  await setup(page)
  await openApp(page)
  await menu(page)
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Delete Agent App', exact: true })
  await expect(dialog).toContainText('Development Studio')
  await expect(dialog).toContainText('data and backups will be kept')
  expect(await requests(page)).toEqual([])
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(await requests(page)).toEqual([])
  await menu(page)
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await dialog.screenshot({ path: info.outputPath('delete-confirmation.png') })
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Deleting…', exact: true })).toBeDisabled()
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  const [request] = await requests(page)
  expect(await requests(page)).toHaveLength(1)
  expect(request).toMatchObject({ verb: 'remove', path: app.path, appId: app.id, confirm: app.id, stopFirst: true })
  await reply(page, request.requestId, { status: 'success', data: { ok: true, removed: { id: app.id, path: app.path } } })
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('iframe[data-framework]')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'App view', exact: true })).toHaveCount(0)
  await list(page, [])
  await expect(page.getByRole('button', { name: 'Open Development Studio', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).panelRequests.some((r: any) => r.type === 'agent_app_delete'))).toBe(false)
})

test('a failed removal keeps the app and disconnect never replays the request', async ({ page }) => {
  await setup(page)
  await menu(page)
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Delete Agent App', exact: true })
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click()
  const [request] = await requests(page)
  await reply(page, request.requestId, { status: 'error', stderr: 'Stop the development instance first.', data: { ok: false } })
  await expect(dialog.getByRole('alert')).toHaveText('Stop the development instance first.')
  await page.evaluate(() => (window as any).panelStore.dispatch({ type: 'connection/setConnected', payload: false }))
  await expect(dialog.getByRole('button', { name: 'Delete', exact: true })).toBeDisabled()
  await page.evaluate(() => (window as any).panelStore.dispatch({ type: 'connection/setConnected', payload: true }))
  await list(page)
  await expect(dialog.getByRole('button', { name: 'Delete', exact: true })).toBeEnabled()
  expect(await requests(page)).toHaveLength(1)
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Open Development Studio', exact: true })).toBeVisible()
})

test('collapsed sidebar supports Delete and an identity change cancels eligibility', async ({ page }) => {
  await setup(page)
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
  await page.getByRole('button', { name: 'Agent App', exact: true }).click()
  await menu(page)
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Delete Agent App', exact: true })
  await list(page, [{ ...app, id: 'replacement' }])
  await expect(dialog.getByRole('button', { name: 'Delete', exact: true })).toBeDisabled()
  await list(page)
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Deleting…', exact: true })).toBeDisabled()
  expect(await requests(page)).toHaveLength(1)
})
